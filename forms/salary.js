  /* JPEG -> এক পাতার PDF (Legal: ৬১২×১০০৮ pt = ৮.৫×১৪ ইঞ্চি; ছবি ২৫৫০×৪২০০ px = ৩০০ ডিপিআই) */
  function pdfFromJpeg(jpg, w, h){
    var enc = new TextEncoder(), parts = [], offs = [], len = 0;
    function push(x){ var u = typeof x === 'string' ? enc.encode(x) : x; parts.push(u); len += u.length; }
    function obj(n, head, stream){ offs[n] = len; push(n + ' 0 obj\n' + head + '\n'); if(stream){ push('stream\n'); push(stream); push('\nendstream\n'); } push('endobj\n'); }
    push('%PDF-1.4\n');
    var content = 'q 612 0 0 1008 0 0 cm /Im0 Do Q';
    obj(1, '<< /Type /Catalog /Pages 2 0 R >>');
    obj(2, '<< /Type /Pages /Kids [3 0 R] /Count 1 >>');
    obj(3, '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 1008] /Resources << /XObject << /Im0 4 0 R >> >> /Contents 5 0 R >>');
    obj(4, '<< /Type /XObject /Subtype /Image /Width ' + w + ' /Height ' + h + ' /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ' + jpg.length + ' >>', jpg);
    obj(5, '<< /Length ' + content.length + ' >>', content);
    var xo = len, x = 'xref\n0 6\n0000000000 65535 f \n';
    for(var i = 1; i <= 5; i++) x += ('0000000000' + offs[i]).slice(-10) + ' 00000 n \n';
    push(x + 'trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n' + xo + '\n%%EOF\n');
    return new Blob(parts, { type: 'application/pdf' });
  }

